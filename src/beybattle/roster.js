export function abilityPower(cfg){return ABILITY_POWER[cfg.role]?.[cfg.special]??1;}
export function abilityDescription(cfg){
 const p=abilityPower(cfg),n=v=>Math.round(v*p*10)/10;
 switch(cfg.special){
  case 'rush':return `A homing rush that adds ${n(14)} spin damage to your next hit. Guard can block it.`;
  case 'wave':return `Deal ${n(14)} spin damage with a shockwave and push your rival away. Guard can block it.`;
  case 'guard':return `Recover ${n(7)} spin. Reduce incoming damage by ${Math.round(65*p)}% for 3 seconds.`;
  case 'mend':return `Recover ${n(15)} spin. Save it for when your spin is running low.`;
  case 'counter':return `Recover ${n(4)} spin. Block ${Math.round(35*p)}% damage and reflect part back for 3 seconds.`;
  case 'drain':return `Steal up to ${n(8)} spin and recover the amount taken. Guard reduces the steal.`;
  default:return SPECIALS[cfg.special].text;
 }
}
